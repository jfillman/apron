#!/usr/bin/env bash
# Vendor Hangar's Clearance policy bundle (autopilot policy/hangar/bundle.json at a gateway tag) into
# templates/55-clearance/clearance-config/bundle-hangar.yaml, the ConfigMap the clearance chart mounts
# (policy.bundles). Re-run with the new tag whenever versions.autopilot.gateway moves.
#   hack/vendor-clearance-bundle.sh gateway-v0.4.0 [path-to-autopilot-checkout]
set -euo pipefail
tag="${1:?usage: $0 <gateway tag> [autopilot checkout]}"
src="${2:-$(cd "$(dirname "$0")/../.." && pwd)/autopilot}"
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/templates/55-clearance/clearance-config/bundle-hangar.yaml"
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
git -C "$src" show "$tag:policy/hangar/bundle.json" > "$tmp"
sum="$(shasum -a 256 < "$tmp" | cut -d' ' -f1)"
python3 - "$tag" "$sum" "$out" "$tmp" <<'PY'
import json, sys
tag, digest, out, path = sys.argv[1:5]
raw = open(path, encoding="utf-8").read()
doc = json.loads(raw)
# The file's own bytes (the core names a bundle's digest in its decisions): a literal block keeps them, but for the
# final newline.
body = raw
with open(out, "w") as fh:
    fh.write(f"""# Hangar's Clearance policy bundle (clearance.policy/v1, {doc['name']} {doc['version']}): autopilot
# policy/hangar/bundle.json at {tag} (sha256 {digest} of that file). Generated by
# hack/vendor-clearance-bundle.sh: do not edit; re-run it when versions.autopilot.gateway moves.
apiVersion: v1
kind: ConfigMap
metadata:
  name: clearance-bundle-hangar
  namespace: @@CLEARANCE_NAMESPACE@@
  labels: {{hangar.io/component: clearance}}
  annotations:
    hangar.io/bundle-source: "autopilot@{tag}:policy/hangar/bundle.json"
    hangar.io/bundle-sha256: "{digest}"
data:
  bundle.json: |
""")
    for line in body.splitlines():
        fh.write("    " + line + "\n")
PY
echo "wrote $out from $tag ($sum)"
